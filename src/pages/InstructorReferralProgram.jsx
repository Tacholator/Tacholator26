import React, { useState } from 'react';
import { base44 } from '@/api/base44Client';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Users, Search, CheckCircle, Clock } from 'lucide-react';
import { format } from 'date-fns';

export default function InstructorReferralProgram() {
  const queryClient = useQueryClient();
  const [search, setSearch] = useState('');
  const [redeemingId, setRedeemingId] = useState(null);
  const [redeemName, setRedeemName] = useState('');

  const { data: user } = useQuery({
    queryKey: ['currentUser'],
    queryFn: () => base44.auth.me(),
  });

  const { data: referrals = [], isLoading } = useQuery({
    queryKey: ['instructorReferrals', user?.id],
    queryFn: async () => {
      const instructorProfile = await base44.entities.Instructor.filter({ created_by: user.email });
      if (!instructorProfile[0]) return [];
      return base44.entities.Referral.filter({ instructorId: instructorProfile[0].id });
    },
    enabled: !!user?.email,
  });

  const { mutate: markRedeemed, isPending } = useMutation({
    mutationFn: async ({ id }) => {
      return base44.entities.Referral.update(id, {
        status: 'redeemed',
        redeemedAt: new Date().toISOString(),
        redeemedByName: redeemName,
      });
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['instructorReferrals'] });
      setRedeemingId(null);
      setRedeemName('');
    },
  });

  const filtered = referrals.filter(r =>
    r.pupilName?.toLowerCase().includes(search.toLowerCase()) ||
    r.code?.toLowerCase().includes(search.toLowerCase())
  );

  const activeCount = referrals.filter(r => r.status === 'active').length;
  const redeemedCount = referrals.filter(r => r.status === 'redeemed').length;

  return (
    <div className="p-6 lg:p-8 max-w-4xl mx-auto">
      <div className="mb-6">
        <h1 className="text-2xl font-bold text-[#071739] flex items-center gap-2">
          <Users className="w-6 h-6 text-[#F7B602]" />
          Referral Program
        </h1>
        <p className="text-slate-500 text-sm mt-1">Track referral codes generated by your pupils.</p>
      </div>

      {/* Stats */}
      <div className="grid grid-cols-2 gap-4 mb-6">
        <Card className="border-0 shadow-sm">
          <CardContent className="p-4 flex items-center gap-3">
            <div className="w-10 h-10 bg-blue-50 rounded-xl flex items-center justify-center">
              <Clock className="w-5 h-5 text-blue-500" />
            </div>
            <div>
              <p className="text-2xl font-bold text-[#071739]">{activeCount}</p>
              <p className="text-xs text-slate-500">Active Codes</p>
            </div>
          </CardContent>
        </Card>
        <Card className="border-0 shadow-sm">
          <CardContent className="p-4 flex items-center gap-3">
            <div className="w-10 h-10 bg-green-50 rounded-xl flex items-center justify-center">
              <CheckCircle className="w-5 h-5 text-green-500" />
            </div>
            <div>
              <p className="text-2xl font-bold text-[#071739]">{redeemedCount}</p>
              <p className="text-xs text-slate-500">Redeemed</p>
            </div>
          </CardContent>
        </Card>
      </div>

      {/* Search */}
      <div className="relative mb-4">
        <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-slate-400" />
        <Input
          placeholder="Search by pupil name or code..."
          value={search}
          onChange={e => setSearch(e.target.value)}
          className="pl-9"
        />
      </div>

      {/* Referrals List */}
      <Card className="border-0 shadow-sm">
        <CardHeader className="border-b border-slate-100 pb-4">
          <CardTitle className="text-base">All Referral Codes</CardTitle>
        </CardHeader>
        <CardContent className="p-0">
          {isLoading ? (
            <div className="flex justify-center py-12">
              <div className="w-6 h-6 border-2 border-[#F7B602] border-t-transparent rounded-full animate-spin" />
            </div>
          ) : filtered.length === 0 ? (
            <div className="text-center py-12 text-slate-400">
              <Users className="w-10 h-10 mx-auto mb-3 opacity-30" />
              <p className="text-sm">No referral codes yet.</p>
              <p className="text-xs mt-1">Codes appear here when your pupils generate them.</p>
            </div>
          ) : (
            <div className="divide-y divide-slate-100">
              {filtered.map((referral) => (
                <div key={referral.id} className="p-4 flex items-center justify-between gap-4">
                  <div className="flex-1 min-w-0">
                    <p className="font-semibold text-[#071739] truncate">{referral.pupilName || 'Unknown Pupil'}</p>
                    <p className="text-xs text-slate-400 mt-0.5">{referral.pupilEmail}</p>
                    <div className="flex items-center gap-2 mt-2">
                      <span className="font-mono text-sm font-bold text-[#071739] bg-slate-100 px-2 py-0.5 rounded">
                        {referral.code}
                      </span>
                      <Badge className={referral.status === 'redeemed' ? 'bg-green-100 text-green-700' : 'bg-blue-100 text-blue-700'}>
                        {referral.status === 'redeemed' ? 'Redeemed' : 'Active'}
                      </Badge>
                    </div>
                    {referral.status === 'redeemed' && (
                      <p className="text-xs text-slate-400 mt-1">
                        Used by <strong>{referral.redeemedByName || 'Unknown'}</strong>
                        {referral.redeemedAt && ` · ${format(new Date(referral.redeemedAt), 'd MMM yyyy')}`}
                      </p>
                    )}
                    <p className="text-xs text-slate-300 mt-1">
                      Generated {referral.created_date ? format(new Date(referral.created_date), 'd MMM yyyy') : ''}
                    </p>
                  </div>

                  {referral.status === 'active' && (
                    <div>
                      {redeemingId === referral.id ? (
                        <div className="flex flex-col gap-2 items-end">
                          <Input
                            placeholder="Referee's name"
                            value={redeemName}
                            onChange={e => setRedeemName(e.target.value)}
                            className="w-36 text-sm h-8"
                          />
                          <div className="flex gap-1">
                            <Button
                              size="sm"
                              onClick={() => markRedeemed({ id: referral.id })}
                              disabled={isPending || !redeemName.trim()}
                              className="bg-green-500 hover:bg-green-600 text-white h-7 text-xs"
                            >
                              Confirm
                            </Button>
                            <Button
                              size="sm"
                              variant="ghost"
                              onClick={() => { setRedeemingId(null); setRedeemName(''); }}
                              className="h-7 text-xs"
                            >
                              Cancel
                            </Button>
                          </div>
                        </div>
                      ) : (
                        <Button
                          size="sm"
                          variant="outline"
                          onClick={() => setRedeemingId(referral.id)}
                          className="text-xs"
                        >
                          Mark Redeemed
                        </Button>
                      )}
                    </div>
                  )}
                </div>
              ))}
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}